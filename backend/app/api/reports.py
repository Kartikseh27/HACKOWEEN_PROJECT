"""
Agricultural Reports API Router.
Endpoints:
- POST /api/report/generate (consumed by frontend src/services/api.ts)
- POST /api/reports/generate (master prompt Section 13)
- GET /api/reports/{report_id}/download (PDF file download)
- GET /api/reports/list (retrieves stored farmer dossiers)
"""

import json
import os
import uuid
from datetime import datetime
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import FileResponse
from sqlalchemy.orm import Session

from app.schemas import FarmerReportPayloadSchema
from app.services.pdf_service import generate_agricultural_pdf, REPORTS_DIR
from app.database import get_db
from app.models import FarmerReportModel

router = APIRouter(prefix="/api", tags=["Agricultural Reports & Dossiers"])


@router.post("/report/generate", response_model=FarmerReportPayloadSchema)
def generate_report(
    payload: FarmerReportPayloadSchema,
    db: Session = Depends(get_db),
):
    """
    Generates a formal agronomic report and creates an actual downloadable PDF.
    Persists report metadata in the SQLite database.
    """
    try:
        report_id = payload.reportId or f"KC-REP-{uuid.uuid4().hex[:6].upper()}"
        generated_date = payload.generatedAt or datetime.utcnow().strftime("%d %B %Y")
        
        report_dict = payload.model_dump()
        report_dict["reportId"] = report_id
        report_dict["generatedAt"] = generated_date

        # Generate real physical PDF document
        pdf_path = generate_agricultural_pdf(report_dict)
        report_dict["pdfPath"] = pdf_path

        # Persist in SQLite
        db_report = db.query(FarmerReportModel).filter(FarmerReportModel.report_id == report_id).first()
        if not db_report:
            db_report = FarmerReportModel(
                report_id=report_id,
                title=payload.title,
                state=payload.farmerLocation.state,
                district=payload.farmerLocation.district,
                village=payload.farmerLocation.village or "",
                crop_name=payload.cropName,
                tools_used_json=json.dumps(payload.toolsUsed),
                executive_summary=payload.executiveSummary,
                action_priorities_json=json.dumps([p.model_dump() for p in payload.actionPriorities]),
                disclaimers_json=json.dumps(payload.disclaimers),
                pdf_path=pdf_path,
            )
            db.add(db_report)
            db.commit()

        return FarmerReportPayloadSchema(**report_dict)
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Report generation failed: {str(exc)}"
        )


@router.post("/reports/generate", response_model=FarmerReportPayloadSchema)
def reports_generate_alias(
    payload: FarmerReportPayloadSchema,
    db: Session = Depends(get_db),
):
    """Alias for POST /api/report/generate specified in master prompt Section 13."""
    return generate_report(payload=payload, db=db)


@router.get("/reports/{report_id}/download")
def download_report(report_id: str, db: Session = Depends(get_db)):
    """
    Downloads the physical PDF document generated by ReportLab.
    Returns FileResponse with Content-Disposition attachment.
    """
    # Check in database
    db_report = db.query(FarmerReportModel).filter(FarmerReportModel.report_id == report_id).first()
    if db_report and db_report.pdf_path and os.path.exists(db_report.pdf_path):
        pdf_file = db_report.pdf_path
    else:
        # Check standard directory
        pdf_file = os.path.join(REPORTS_DIR, f"{report_id}.pdf")

    if not os.path.exists(pdf_file):
        raise HTTPException(
            status_code=404,
            detail=f"Report PDF '{report_id}' was not found. Please generate the report first."
        )

    return FileResponse(
        path=pdf_file,
        media_type="application/pdf",
        filename=f"Kisan_Culture_{report_id}.pdf",
    )


@router.get("/reports/list")
def list_reports(db: Session = Depends(get_db)):
    """Retrieves all previously generated reports from SQLite."""
    try:
        reports = db.query(FarmerReportModel).order_by(FarmerReportModel.generated_at.desc()).all()
        return {"reports": [r.to_dict() for r in reports]}
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Failed to list reports: {str(exc)}"
        )

